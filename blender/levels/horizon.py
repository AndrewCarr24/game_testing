"""Render the horizon band seen through the house's windows and from its lawn: the real Blue Ridge
surroundings of the estate, from the wilderness level the gate opens onto (Laurel Fork Cove,
design/wilderness/blue_ridge/; generated by blender/wilderness/levels/laurel_fork.py into
build/wilderness/<world>/world/). Seen from the house: the hay meadow and the forest wall past
the hedge, the cove's rim and Laurel Ridge with its three lookouts to the south, Raven Spur to the
east, the Narrows and the river valley toward the town to the west, the ring's ridges north, and
beyond them the layered blue ridgelines of the wild sky (viewer/wild/sky_wild.js, same formula),
all under the level's sun with the brief's haze (32 km visual range, blue away from the sun and
peach toward it, viewer/wild/atmosphere.js hazeAlong). design/wilderness/estate_link.md.

  /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup \
      --python blender/levels/horizon.py -- [samples] [--world laurel_fork] [--width 4096] [--fields]

What goes in (all in the estate frame = this scene's Blender frame: x east, y north, z up, the
house at the origin; the wild's three.js frame is (x, height, -(y + 810))):
  terrain      the 1.5 m heightfield (every 2nd sample, 3 m), coloured from its splat by the wild's
               palette (grass / litter / gneiss / trail), hay where the meadow is; lit by Cycles
  backdrop     the 4.6 km ring (12 m), its baked colour drawn as it is in the wild (emission:
               colour x light_scale x 1.15, the crown mottle)
  forest       every tree and big shrub the wild places (inst_*.bin, the ring's forest too), as the
               vegetation kit's LOD1 models (build/wilderness/veg), instanced by geometry nodes
  water        the river and Laurel Fork (water16.png), the county road (road.json)
  town         the town's glimpse props (world.json town), as boxes
  far ridges   composited after the render where the sky still shows: sky_wild.js's eight layers
The house, its grounds and the hedge are left out: they are real geometry in front of the band
(plan.GROUNDS). The ground under them (the lawn rect, held at lawn height) stays in, so the band
has no holes under the horizon seen from anywhere on the grounds.

Writes assets/textures/T_Mansion_Horizon.webp (RGBA: alpha 0 where the sky shows; the engine draws
the sky itself behind it), assets/levels/mansion_sky.json (latitude range, brightness scale, sky
colours) and build/horizon_preview.png (the band over the house's sky, for looking at). The band
is an equirectangular strip in three.js's convention (the engine reads it with the same u as an
equirect environment map). One panorama from the house works from anywhere on the grounds: the
nearest of it is ~80 m away. (The old generic fields-and-hills band is in git history, before
estate_link; --fields only says so.) --nowater leaves the water out (a debugging aid).
"""
