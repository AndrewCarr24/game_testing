SUN_H = (1.0, 0.0)           # the sun's horizontal direction (Blender x, y), set in main


def add_haze(m, emission_only=False):
    """Aerial perspective inside the material: T = exp(-EXT d) (d = the distance from the camera);
    the surface's colour is scaled by T and it emits the air light x (1 - T), the air light
    direction-dependent as the wild's hazeAlong (blue away from the sun, peach toward it). In the
    Principled BSDF itself (not a shader mix), so alpha-cut leaves stay cut. emission_only: the
    material is an Emission shader (the backdrop): its colour is mixed instead."""
    if not m or not m.use_nodes or "_haze" in m:
        return
    nodes, links = m.node_tree.nodes, m.node_tree.links
    bsdf = next((n for n in nodes if n.type == "BSDF_PRINCIPLED"), None)
    emis = next((n for n in nodes if n.type == "EMISSION"), None) if emission_only else None
    if bsdf is None and emis is None:
        return
    m["_haze"] = True
    cam = nodes.new("ShaderNodeCameraData")
    mul = nodes.new("ShaderNodeMath"); mul.operation = "MULTIPLY"; mul.inputs[1].default_value = -EXT
    links.new(cam.outputs["View Distance"], mul.inputs[0])
    T = nodes.new("ShaderNodeMath"); T.operation = "EXPONENT"
    links.new(mul.outputs[0], T.inputs[0])
    f = nodes.new("ShaderNodeMath"); f.operation = "SUBTRACT"; f.inputs[0].default_value = 1.0
    links.new(T.outputs[0], f.inputs[1])
    # air light: s = max(0, dot(horizontal view dir, horizontal sun dir))^3
    geo = nodes.new("ShaderNodeNewGeometry")
    flat = nodes.new("ShaderNodeVectorMath"); flat.operation = "MULTIPLY"; flat.inputs[1].default_value = (-1, -1, 0)
    links.new(geo.outputs["Incoming"], flat.inputs[0])
    nrm = nodes.new("ShaderNodeVectorMath"); nrm.operation = "NORMALIZE"
    links.new(flat.outputs[0], nrm.inputs[0])
    dot = nodes.new("ShaderNodeVectorMath"); dot.operation = "DOT_PRODUCT"; dot.inputs[1].default_value = (SUN_H[0], SUN_H[1], 0)
    links.new(nrm.outputs[0], dot.inputs[0])
    mx = nodes.new("ShaderNodeMath"); mx.operation = "MAXIMUM"; mx.inputs[1].default_value = 0.0
    links.new(dot.outputs["Value"], mx.inputs[0])
    p3 = nodes.new("ShaderNodeMath"); p3.operation = "POWER"; p3.inputs[1].default_value = 3.0
    links.new(mx.outputs[0], p3.inputs[0])
    air = nodes.new("ShaderNodeMix"); air.data_type = "RGBA"
    air.inputs["A"].default_value = (*[v * HAZE_SCALE for v in hexlin(HAZE_AWAY)], 1)
    air.inputs["B"].default_value = (*[v * HAZE_SCALE for v in hexlin(HAZE_SUN)], 1)
    links.new(p3.outputs[0], air.inputs["Factor"])
    if emis is not None:
        col = emis.inputs["Color"]
        mix = nodes.new("ShaderNodeMix"); mix.data_type = "RGBA"
        if col.is_linked:
            links.new(col.links[0].from_socket, mix.inputs["B"])
        else:
            mix.inputs["B"].default_value = col.default_value
        links.new(air.outputs["Result"], mix.inputs["A"])
        links.new(T.outputs[0], mix.inputs["Factor"])
        links.new(mix.outputs["Result"], col)
        return
    base = bsdf.inputs["Base Color"]
    dark = nodes.new("ShaderNodeMix"); dark.data_type = "RGBA"
    dark.inputs["A"].default_value = (0, 0, 0, 1)
    if base.is_linked:
        links.new(base.links[0].from_socket, dark.inputs["B"])
    else:
        dark.inputs["B"].default_value = base.default_value
    links.new(T.outputs[0], dark.inputs["Factor"])
    links.new(dark.outputs["Result"], base)
    links.new(air.outputs["Result"], bsdf.inputs["Emission Color"])
    links.new(f.outputs[0], bsdf.inputs["Emission Strength"])


def principled(name, color=None, attr=None, rough=0.95):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nodes, links = m.node_tree.nodes, m.node_tree.links
    bsdf = next(n for n in nodes if n.type == "BSDF_PRINCIPLED")
    bsdf.inputs["Roughness"].default_value = rough
    # (grass, litter and gravel don't mirror the sky at grazing angles: from the house, 1-3 deg over
    # the meadow, the default specular turned the flat pads into a pale lake)
    if rough > 0.5:
        for k in ("Specular IOR Level", "Specular"):
            if k in bsdf.inputs:
                bsdf.inputs[k].default_value = 0.0
    if attr:
        a = nodes.new("ShaderNodeAttribute"); a.attribute_name = attr
        links.new(a.outputs["Color"], bsdf.inputs["Base Color"])
    elif color:
        bsdf.inputs["Base Color"].default_value = (*color, 1)
    return m


def emissive(name, attr, scale, mottle_m=14.0):
    """Emission = vertex colour x scale x a crown mottle (level.js buildBackdrop)."""
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nodes, links = m.node_tree.nodes, m.node_tree.links
    for n in list(nodes):
        if n.type == "BSDF_PRINCIPLED":
            nodes.remove(n)
    out = next(n for n in nodes if n.type == "OUTPUT_MATERIAL")
    em = nodes.new("ShaderNodeEmission")
    a = nodes.new("ShaderNodeAttribute"); a.attribute_name = attr
    geo = nodes.new("ShaderNodeNewGeometry")
    noise = nodes.new("ShaderNodeTexNoise"); noise.inputs["Scale"].default_value = 1.0 / mottle_m
    noise.inputs["Detail"].default_value = 1.0
    links.new(geo.outputs["Position"], noise.inputs["Vector"])
    mr = nodes.new("ShaderNodeMapRange"); mr.inputs["To Min"].default_value = 0.75 * scale; mr.inputs["To Max"].default_value = 1.25 * scale
    links.new(noise.outputs["Fac"], mr.inputs["Value"])
    mul = nodes.new("ShaderNodeMix"); mul.data_type = "RGBA"; mul.blend_type = "MULTIPLY"; mul.inputs["Factor"].default_value = 1.0
    links.new(a.outputs["Color"], mul.inputs["A"])
    links.new(mr.outputs["Result"], mul.inputs["B"])
    links.new(mul.outputs["Result"], em.inputs["Color"])
    links.new(em.outputs["Emission"], out.inputs["Surface"])
    return m


def make_mesh(name, verts, faces, col, mat, colors=None, smooth=True):
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts.tolist() if hasattr(verts, "tolist") else verts, [], faces.tolist() if hasattr(faces, "tolist") else faces)
    me.materials.append(mat)
    if colors is not None:
        ca = me.color_attributes.new("Col", "FLOAT_COLOR", "POINT")
        rgba = np.concatenate([colors, np.ones((len(colors), 1))], axis=1).astype(np.float32)
        ca.data.foreach_set("color", rgba.ravel())
    if smooth:
        me.polygons.foreach_set("use_smooth", np.ones(len(me.polygons), bool))
    me.update()
    ob = bpy.data.objects.new(name, me)
    col.objects.link(ob)
    return ob


def grid_faces(nx, ny, keep):
    """Quads of an nx x ny vertex grid (row-major, i fastest), where keep[j, i] (per quad) is True."""
    j, i = np.nonzero(keep)
    a = j * nx + i
    return np.column_stack([a, a + 1, a + nx + 1, a + nx])


