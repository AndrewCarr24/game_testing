def kit_proto(model, lod=1):
    """Import a vegetation kit glTF once; its LOD node's meshes go into a collection kept out of
    the scene (an instance prototype). Returns (collection, height m) or None."""
    path = os.path.join(PROJECT, "build", "wilderness", "veg", f"{model}.gltf")
    if not os.path.exists(path):
        return None
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=path)
    new = [o for o in bpy.data.objects if o not in before]
    node = f"Veg_{model[0].upper() + model[1:]}_LOD{lod}"
    root = next((o for o in new if o.name.startswith(node)), None)
    if root is None:
        root = next((o for o in new if o.name.startswith(f"Veg_{model[0].upper() + model[1:]}_LOD")), None)
    if root is None:
        for o in new:
            bpy.data.objects.remove(o)
        return None
    keep = [root] + [o for o in root.children_recursive]
    coll = bpy.data.collections.new(f"Proto_{model}")
    bpy.context.view_layer.update()
    zmin, zmax = 1e9, -1e9
    for o in keep:
        for c in list(o.users_collection):
            c.objects.unlink(o)
        coll.objects.link(o)
        if o.type == "MESH":
            for v in o.bound_box:
                p = o.matrix_world @ Vector(v)
                zmin, zmax = min(zmin, p.z), max(zmax, p.z)
    for o in new:
        if o not in keep:
            bpy.data.objects.remove(o)
    return coll, max(zmax, 0.5)


def proxy_proto(kind, tint):
    """A stand-in crown (no kit model): an ellipsoid on a trunk, unit height."""
    import bmesh
    bm = bmesh.new()
    if kind == "conifer":
        bmesh.ops.create_cone(bm, cap_ends=True, segments=8, radius1=0.22, radius2=0.01, depth=0.85,
                              matrix=__import__("mathutils").Matrix.Translation((0, 0, 0.57)))
    else:
        r = bmesh.ops.create_icosphere(bm, subdivisions=2, radius=1.0)
        for v in r["verts"]:
            v.co = Vector((v.co.x * 0.3, v.co.y * 0.3, v.co.z * 0.32 + 0.62))
    me = bpy.data.meshes.new(f"Proxy_{kind}")
    bm.to_mesh(me); bm.free()
    me.materials.append(principled(f"M_Proxy_{kind}_{len(bpy.data.materials)}", color=tint))
    ob = bpy.data.objects.new(me.name, me)
    coll = bpy.data.collections.new(f"Proto_proxy_{kind}_{len(bpy.data.collections)}")
    coll.objects.link(ob)
    return coll, 1.0


def instancer(col, name, proto, pts, scale, rot):
    """A point mesh (the instance positions, 'scale' and 'rot' attributes) with a geometry-nodes
    modifier: Instance on Points of the prototype collection."""
    me = bpy.data.meshes.new(name)
    me.from_pydata(pts.tolist(), [], [])
    a = me.attributes.new("scale", "FLOAT", "POINT"); a.data.foreach_set("value", scale.astype(np.float32))
    b = me.attributes.new("rot", "FLOAT", "POINT"); b.data.foreach_set("value", rot.astype(np.float32))
    ob = bpy.data.objects.new(name, me)
    col.objects.link(ob)
    ng = bpy.data.node_groups.new(f"GN_{name}", "GeometryNodeTree")
    ng.interface.new_socket(name="Geometry", in_out="INPUT", socket_type="NodeSocketGeometry")
    ng.interface.new_socket(name="Geometry", in_out="OUTPUT", socket_type="NodeSocketGeometry")
    N, L = ng.nodes, ng.links
    gi, go = N.new("NodeGroupInput"), N.new("NodeGroupOutput")
    ci = N.new("GeometryNodeCollectionInfo")
    ci.inputs["Collection"].default_value = proto
    ci.inputs["Separate Children"].default_value = False
    ci.inputs["Reset Children"].default_value = False
    iop = N.new("GeometryNodeInstanceOnPoints")
    sa = N.new("GeometryNodeInputNamedAttribute"); sa.data_type = "FLOAT"; sa.inputs["Name"].default_value = "scale"
    ra = N.new("GeometryNodeInputNamedAttribute"); ra.data_type = "FLOAT"; ra.inputs["Name"].default_value = "rot"
    cx = N.new("ShaderNodeCombineXYZ")
    L.new(ra.outputs["Attribute"], cx.inputs["Z"])
    L.new(gi.outputs["Geometry"], iop.inputs["Points"])
    L.new(ci.outputs[0], iop.inputs["Instance"])
    L.new(cx.outputs["Vector"], iop.inputs["Rotation"])
    L.new(sa.outputs["Attribute"], iop.inputs["Scale"])
    L.new(iop.outputs["Instances"], go.inputs["Geometry"])
    mod = ob.modifiers.new("Instances", "NODES")
    mod.node_group = ng
    return ob


def forest(col, D, meta, height_fn):
    """Every tree and big shrub the wild places, by species, with the kit's LOD1 models (or a
    proxy when the kit lacks one). Instances inside the lawn rect (none) and ground cover skipped."""
    vegj = os.path.join(PROJECT, "build", "wilderness", "veg", "veg.json")
    kit = json.load(open(vegj)) if os.path.exists(vegj) else {}
    models = (kit.get("kits", {}).get("blue_ridge") or {}).get("species", {})
    half = meta["size"] / 2
    hmin, hrange = meta["height"]["min"], meta["height"]["max"] - meta["height"]["min"]
    protos = {}
    total = 0
    for sid, info in meta["species"].items():
        if not info.get("count") or info.get("tier") == "under":
            continue
        if info.get("tier") == "shrub" and info.get("height", 0) < 1.8:
            continue
        q = np.fromfile(os.path.join(D, info["file"]), dtype=np.uint16)
        if info.get("fmt") == "xz4":
            continue
        q = q.reshape(-1, 6).astype(np.float64)
        Bd = info.get("bounds")
        bx = (Bd["x"][0], Bd["x"][1] - Bd["x"][0]) if Bd else (-half, meta["size"])
        bz = (Bd["z"][0], Bd["z"][1] - Bd["z"][0]) if Bd else (-half, meta["size"])
        bh = (Bd["h"][0], Bd["h"][1] - Bd["h"][0]) if Bd else (hmin, hrange)
        x3 = q[:, 0] / 65535 * bx[1] + bx[0]
        z3 = q[:, 1] / 65535 * bz[1] + bz[0]
        y3 = q[:, 2] / 65535 * bh[1] + bh[0]
        size = q[:, 3] / 10000.0
        rot = q[:, 4] / 65535 * 2 * math.pi
        BXp, BYp = x3, -z3 - OY
        keep = ~((np.abs(BXp) < LAWN[0]) & (np.abs(BYp) < LAWN[1]))
        model = (info.get("veg_ids") or [sid])[0]
        key = model
        if key not in protos:
            vid = (models.get(model) or [model])[0]
            protos[key] = kit_proto(vid) or proxy_proto("conifer" if info["kind"] in ("conifer", "pine") else "broadleaf",
                                                    tuple(srgb_lin(info.get("tint_rgb", (0.3, 0.4, 0.2)))))
        coll, mh = protos[key]
        s = size * info["height"] / mh
        pts = np.column_stack([BXp, BYp, y3])[keep]
        # (three's rotY turns +x toward -z; Blender's z rotation turns +x toward +y: the same sense
        # after the frame flip)
        instancer(col, f"Trees_{sid}", coll, pts, s[keep], rot[keep])
        total += int(keep.sum())
        print(f"  {sid}: {int(keep.sum())} instances of {model} (model {mh:.1f} m)")
    total += ring_forest(col, D, meta, protos)
    return total


# The ring's forest, for the band only: the wild draws its 4.6 km backdrop as a canopy-coloured
# surface (fine from its lookouts, 1 km up), but from the house, low in the gap, the ring's near
# ridges are the skyline north, east and west and need real crowns. Mixed cove / oak forest on
# every ring slope 0.35-3 km out, except the cleared valley floors (flat and low: pastures, the
# river's corridor, the town's basin) and rock; the wild's own ring trees (river valley) are
# placed above with the rest.
RING_MIX = [("tulip_poplar", 0.28), ("northern_red_oak", 0.24), ("chestnut_oak", 0.14), ("shagbark_hickory", 0.1),
            ("sugar_maple", 0.1), ("white_pine", 0.09), ("eastern_hemlock", 0.05)]


def ring_forest(col, D, meta, protos, spacing=10.5, r_max=3000.0):
    B = meta["backdrop"]
    bh = wt.read_png_fast(os.path.join(D, "backdrop16.png")).astype(np.float64) / 65535.0 * (B["max"] - B["min"]) + B["min"]
    n, c = bh.shape[0], B["cell"]
    x0 = -B["extent"] / 2
    gy, gx = np.gradient(bh, c)
    slope = np.degrees(np.arctan(np.hypot(gx, gy)))
    rng = np.random.default_rng(31)
    xs = np.arange(-r_max, r_max, spacing)
    X, Z = np.meshgrid(xs, xs - OY)                              # three z around the house (z = -810)
    X = X + rng.uniform(-0.45, 0.45, X.shape) * spacing
    Z = Z + rng.uniform(-0.45, 0.45, Z.shape) * spacing
    X, Z = X.ravel(), Z.ravel()
    r = np.hypot(X, Z + OY)
    half = meta["size"] / 2
    ok = (r > 160) & (r < r_max) & ~((np.abs(X) < half) & (np.abs(Z) < half))
    u, v = (X - x0) / c, (Z - x0) / c
    i, j = np.clip(u.astype(int), 0, n - 2), np.clip(v.astype(int), 0, n - 2)
    fu, fv = u - i, v - j
    h = bh[j, i] * (1 - fu) * (1 - fv) + bh[j, i + 1] * fu * (1 - fv) + bh[j + 1, i] * (1 - fu) * fv + bh[j + 1, i + 1] * fu * fv
    sl = slope[j, i]
    ok &= ~((sl < 6.0) & (h < 40.0)) & (sl < 46.0)
    # gaps and clumps (a little light through the canopy, irregular edges)
    ok &= rng.random(X.shape) < 0.55 + 0.45 * np.sin(X / 97.0 + np.cos(Z / 131.0) * 2.0) * np.sin(Z / 83.0 + 1.7)
    X, Z, h = X[ok], Z[ok], h[ok]
    pick = rng.choice(len(RING_MIX), size=len(X), p=np.array([w for _, w in RING_MIX]) / sum(w for _, w in RING_MIX))
    out = 0
    for k, (sp, _) in enumerate(RING_MIX):
        info = meta["species"].get(sp)
        proto = protos.get(sp) or (kit_proto(sp) if info else None)
        if not proto or not info:
            continue
        protos[sp] = proto
        m = pick == k
        coll, mh = proto
        s = rng.uniform(0.75, 1.1, m.sum()) * info["height"] / mh
        pts = np.column_stack([X[m], -Z[m] - OY, h[m] - 0.3])
        instancer(col, f"Ring_{sp}", coll, pts, s, rng.uniform(0, 2 * math.pi, m.sum()))
        out += int(m.sum())
    print(f"  ring forest (band only): {out} trees")
    return out


# ---------------------------------------------------------------- the far ridges (sky_wild.js)
def _h1(n):
    return np.modf(np.sin(n * np.float32(127.1)).astype(np.float32) * np.float32(43758.5453))[0] % 1.0


def _vnoise(x):
    i = np.floor(x); f = x - i
    f = f * f * (3 - 2 * f)
    return _h1(i) * (1 - f) + _h1(i + 1) * f


def ridge_shape(a, k):
    s, amp, fr = 0.0, 0.55, 1.0
    for o in range(4):
        s = s + amp * _vnoise((a * fr + k * 17.3 + o * 5.1).astype(np.float32))
        amp *= 0.5; fr *= 2.3
    return s


def far_ridges(w, h, sun3):
    """(h, w, 3) radiance of sky_wild.js's ridgelines and a mask (h, w) where one is hit, per band
    pixel (three.js directions; row 0 = the band's bottom). The air light of the far layers fades
    from the wild's hazeAlong to the house sky's own horizon (the dome above them), so the last
    ridge melts into the house's sky."""
    u = (np.arange(w) + 0.5) / w
    v = (np.arange(h) + 0.5) / h
    az = (u - 0.5) * 2 * math.pi                         # atan(d.z, d.x)
    el = np.radians(LAT[0] + v * (LAT[1] - LAT[0]))
    AZ, EL = np.meshgrid(az, el)
    d = np.stack([np.cos(AZ) * np.cos(EL), np.sin(EL), np.sin(AZ) * np.cos(EL)], -1)
    sun = np.asarray(sun3, float) / np.linalg.norm(sun3)
    s = np.clip(d @ sun, 0, None)
    sh = np.array([sun[0], 0, sun[2]]); sh /= np.linalg.norm(sh)
    dh = d * np.array([1, 0, 1]); dh /= np.linalg.norm(dh, axis=-1, keepdims=True)
    sa = np.clip(dh @ sh, 0, None) ** 3
    away = np.array([v * HAZE_SCALE for v in hexlin(HAZE_AWAY)]); towd = np.array([v * HAZE_SCALE for v in hexlin(HAZE_SUN)])
    hz = away * (1 - sa[..., None]) + towd * sa[..., None]
    s8 = s ** 8
    sky_h = np.array(HORIZON) + np.array([1.0, 0.92, 0.8]) * (0.3 * s8)[..., None]
    col = np.zeros(d.shape)
    hit = np.zeros(EL.shape, bool)
    for k, (L, base, amp, wl) in enumerate(RIDGES):
        crest = base + amp * ridge_shape((AZ / wl * 6.0).astype(np.float32), float(k))
        hh = crest - EYE - L * L / 12742000.0
        top = np.arctan2(hh, L)
        m = (EL < top) & ~hit
        if not m.any():
            continue
        T = math.exp(-EXT * L)
        rc = np.array(RIDGE_COL) * (1 + 0.8 * s * s)[..., None]
        below = (top - EL) * L / max(amp, 1.0)
        pool = np.clip((below - 0.15) / (1.6 - 0.15), 0, 1); pool = pool * pool * (3 - 2 * pool)
        wsky = np.clip((L - 9000.0) / (48000.0 - 9000.0), 0, 1) ** 0.7
        air = hz * (1 - wsky) + sky_h * wsky
        c = air * (1 - T * (1 - 0.55 * pool))[..., None] + rc * (T * (1 - 0.55 * pool))[..., None]
        c = c + (air * 1.06 - c) * (0.18 * pool * (1 - T))[..., None]
        col[m] = c[m]
        hit |= m
    return col, hit


def sky_colour(w, h, sun3):
    """The house's sky dome (sky.js) per band pixel, for the preview."""
    v = (np.arange(h) + 0.5) / h
    el = np.radians(LAT[0] + v * (LAT[1] - LAT[0]))
    u = (np.arange(w) + 0.5) / w
    az = (u - 0.5) * 2 * math.pi
    AZ, EL = np.meshgrid(az, el)
    d = np.stack([np.cos(AZ) * np.cos(EL), np.sin(EL), np.sin(AZ) * np.cos(EL)], -1)
    y = np.clip(d[..., 1], 0, None)
    col = np.where(d[..., 1:2] < 0, np.array(HORIZON) * 0.85, np.array(HORIZON) + (np.array(ZENITH) - np.array(HORIZON)) * np.sqrt(y)[..., None])
    sun = np.asarray(sun3, float) / np.linalg.norm(sun3)
    s = np.clip(d @ sun, 0, None)
    return col + np.array([1.0, 0.92, 0.8]) * (0.3 * s ** 8 + 1.5 * s ** 256)[..., None]


